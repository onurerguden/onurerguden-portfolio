import type { NextConfig } from "next";
import { contentSecurityPolicy } from "./src/lib/security";

// Versioned files change URL when their content changes, so browsers may keep
// them for a year without revalidating.
const immutable = [
  { key: "Cache-Control", value: "public, max-age=31536000, immutable" },
];
const versioned = [{ type: "query" as const, key: "v" }];
// Sent with every response. The policy is the same for every request, so
// pages are built ahead and served from the CDN (src/lib/security.ts).
const security = [
  {
    key: "Content-Security-Policy",
    value: contentSecurityPolicy({
      development: process.env.NODE_ENV === "development",
      // Over plain http (a local production build, CI) WebKit would upgrade
      // every request to an https one that cannot connect.
      secure: !!process.env.VERCEL,
    }),
  },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
  {
    key: "Permissions-Policy",
    value:
      "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
  },
  // Two years, subdomains included; not submitted for preload.
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains",
  },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  experimental: {
    // The root layout lives under the language segment, so paths outside
    // both languages get their own 404 document (app/global-not-found.tsx).
    globalNotFound: true,
  },
  // Local public snapshots are generated by preview:github, never deployed.
  outputFileTracingExcludes: { "/*": ["./work/github/**"] },
  images: {
    // Local images without a query string only, so the optimizer cannot be
    // asked for arbitrary variants. Versioned desk images skip the optimizer
    // (src/lib/desk-asset-urls.ts).
    localPatterns: [{ pathname: "/**", search: "" }],
  },
  // English is the default language (x-default), so the bare origin moves
  // there permanently and search engines index /en rather than /.
  async redirects() {
    // Share cards moved to …/opengraph-image/card (one card per page, with
    // a localized alt); links already shared keep working.
    const card = "(opengraph-image|twitter-image)";
    return [
      { source: "/", destination: "/en", permanent: true },
      ...[
        "/:locale(en|tr)",
        "/:locale(en|tr)/:section(research|projects)",
        "/:locale(en|tr)/projects/:slug",
      ].map((page) => ({
        source: `${page}/:card${card}`,
        destination: `${page.replace(/\([^)]*\)/g, "")}/:card/card`,
        permanent: true,
      })),
    ];
  },
  async rewrites() {
    return [
      { source: "/.well-known/security.txt", destination: "/security.txt" },
    ];
  },
  async headers() {
    return [
      { source: "/:path*", headers: security },
      {
        source: "/:locale(en|tr)/lab/:path*",
        headers: [{ key: "X-Robots-Tag", value: "noindex, nofollow" }],
      },
      {
        source: "/:locale(en|tr)/lab",
        headers: [{ key: "X-Robots-Tag", value: "noindex, nofollow" }],
      },
      // The desk model and its rendered views carry a ?v= content revision.
      { source: "/models/:path*", has: versioned, headers: immutable },
      { source: "/images/desk/:path*", has: versioned, headers: immutable },
      // And the icons, whose links carry their content's revision
      // (src/lib/icons.ts).
      {
        source:
          "/:icon(favicon\\.ico|icon\\.svg|apple-touch-icon\\.png|icon-192\\.png|icon-512\\.png|icon-maskable-512\\.png)",
        has: versioned,
        headers: immutable,
      },
      // So do the Bliss layers (src/lib/bliss-geometry.ts).
      { source: "/images/bliss/:path*", has: versioned, headers: immutable },
      // The decoder's folder is named after the three release it came with.
      {
        source: "/decoders/draco/:release(three-[^/]+)/:file*",
        headers: immutable,
      },
    ];
  },
};

export default nextConfig;
